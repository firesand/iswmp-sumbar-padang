#!/usr/bin/env node

/**
 * Configure or promote an account to a Monitor-Only Admin (Admin Pemantau).
 *
 * Usage:
 *   node scripts/create-or-set-monitor-admin.mjs --email=user@example.com [--apply]
 *   node scripts/create-or-set-monitor-admin.mjs --uid=<UID> [--apply]
 *
 * Requirements for Monitor Admin:
 *   - role: 'admin'
 *   - adminRole: 'viewer'
 *   - isViewer: true
 *   - accountStatus: 'active'
 *   - isActive: true
 *   - mustChangePassword: false
 */

import crypto from 'node:crypto';
import authModule from 'firebase-tools/lib/auth.js';
import accountExporterModule from 'firebase-tools/lib/accountExporter.js';
import {
  createFirebaseCliApi,
  decodeFirestoreDocument,
  encodeFirestoreValue,
} from './lib/firebase-cli-api.mjs';

const PROJECT_ID = process.env.GOOGLE_CLOUD_PROJECT || 'iswmp-sumbar-padang';
const FIRESTORE_ROOT =
  `https://firestore.googleapis.com/v1/projects/${PROJECT_ID}/` +
  'databases/(default)/documents';

const args = process.argv.slice(2);
const APPLY = args.includes('--apply');
const emailArg = args.find(a => a.startsWith('--email='))?.slice('--email='.length);
const uidArg = args.find(a => a.startsWith('--uid='))?.slice('--uid='.length);
const nameArg = args.find(a => a.startsWith('--name='))?.slice('--name='.length);
const passwordArg = args.find(a => a.startsWith('--password='))?.slice('--password='.length);

if (!emailArg && !uidArg) {
  console.log(`
Usage:
  node scripts/create-or-set-monitor-admin.mjs --email=<email> [--name="Nama"] [--password=<pwd>] [--apply]
  node scripts/create-or-set-monitor-admin.mjs --uid=<UID> [--email=<email>] [--name="Nama"] [--apply]

Options:
  --email=<email>       Target user by email
  --uid=<UID>           Target user by UID
  --name=<name>         Name for profile (optional)
  --password=<password> Password if creating new Auth account (optional)
  --apply               Apply changes to Firestore and Auth (default is dry-run)
`);
  process.exit(1);
}

const api = await createFirebaseCliApi();

// Fetch users from Firestore
let targetDoc = null;
let targetUid = uidArg;

if (targetUid) {
  try {
    const doc = await api(`${FIRESTORE_ROOT}/users/${targetUid}`);
    targetDoc = decodeFirestoreDocument(doc);
  } catch (err) {
    if (err.status !== 404) throw err;
  }
} else if (emailArg) {
  const query = new URLSearchParams({ pageSize: '300', showMissing: 'false' });
  const result = await api(`${FIRESTORE_ROOT}/users?${query}`);
  const users = (result.documents || []).map(decodeFirestoreDocument).filter(Boolean);
  targetDoc = users.find(u => u.data?.email?.toLowerCase() === emailArg.toLowerCase());
  if (targetDoc) {
    targetUid = targetDoc.id;
  }
}

// If not found in Firestore, search Firebase Auth
let authAccount = null;
if (!targetUid && emailArg) {
  console.log(`Mencari ${emailArg} di Firebase Authentication...`);
  try {
    await accountExporterModule.serialExportUsers(PROJECT_ID, {
      format: 'json',
      batchSize: 1000,
      writeUsersToFile(userList) {
        for (const user of userList) {
          if (user.email?.toLowerCase() === emailArg.toLowerCase()) {
            authAccount = user;
          }
        }
      },
    });
  } catch (authErr) {
    console.warn('Gagal mencari di Auth exporter:', authErr.message);
  }

  if (authAccount) {
    targetUid = authAccount.localId;
    console.log(`Ditemukan akun di Firebase Auth: UID=${targetUid}`);
  }
}

let generatedPassword = null;
let isNewAuth = false;

if (!targetDoc && !targetUid) {
  if (!emailArg) {
    console.error(`User tidak ditemukan untuk UID ${uidArg}.`);
    process.exit(1);
  }
  isNewAuth = true;
  generatedPassword = passwordArg || (`Admin#${crypto.randomBytes(4).toString('hex')}!`);
  console.log(`Akun ${emailArg} belum terdaftar di Firebase Authentication.`);
  console.log(`Akan dibuatkan akun baru di Authentication & Firestore.`);
}

console.log('\nTarget user status:', {
  uid: targetUid || '(will be generated by Auth)',
  name: nameArg || targetDoc?.data?.name || targetDoc?.data?.displayName || authAccount?.displayName || emailArg?.split('@')[0],
  email: targetDoc?.data?.email || emailArg || authAccount?.email,
  currentRole: targetDoc?.data?.role || '(none)',
  currentAdminRole: targetDoc?.data?.adminRole || '(none)',
  currentIsViewer: targetDoc?.data?.isViewer || false,
  currentStatus: targetDoc?.data?.accountStatus || '(none)',
  currentIsActive: targetDoc?.data?.isActive || false,
  ...(isNewAuth ? { newAuthPassword: generatedPassword } : {}),
});

const updates = {
  role: 'admin',
  adminRole: 'viewer',
  isViewer: true,
  accountStatus: 'active',
  isActive: true,
  mustChangePassword: false,
  updatedAt: new Date().toISOString(),
  email: emailArg || targetDoc?.data?.email || authAccount?.email || '',
  name: nameArg || targetDoc?.data?.name || targetDoc?.data?.displayName || authAccount?.displayName || (emailArg || '').split('@')[0] || 'Admin Pemantau',
  ...(!targetDoc ? { createdAt: new Date().toISOString() } : {}),
};

console.log('\nPlanned updates:');
console.log(JSON.stringify(updates, null, 2));

if (!APPLY) {
  console.log('\n[DRY RUN] Tidak ada perubahan yang disimpan ke Firestore/Auth.');
  console.log('Tambahkan flag --apply untuk menerapkan konfigurasi admin pemantau.');
  process.exit(0);
}

if (isNewAuth) {
  console.log(`\nMembuat akun Authentication untuk ${emailArg}...`);
  const authRes = await api(
    `https://identitytoolkit.googleapis.com/v1/projects/${PROJECT_ID}/accounts`,
    {
      method: 'POST',
      body: JSON.stringify({
        email: emailArg,
        password: generatedPassword,
        displayName: updates.name,
        emailVerified: true,
      }),
    }
  );
  targetUid = authRes.localId;
  console.log(`Akun Authentication berhasil dibuat! UID=${targetUid}`);
}

// Apply patch
const updateMask = Object.keys(updates)
  .map(k => `updateMask.fieldPaths=${encodeURIComponent(k)}`)
  .join('&');

const patchUrl = `${FIRESTORE_ROOT}/users/${targetUid}?${updateMask}`;

const firestoreFields = {};
for (const [k, v] of Object.entries(updates)) {
  if (k.endsWith('At')) {
    firestoreFields[k] = { timestampValue: v };
  } else {
    firestoreFields[k] = encodeFirestoreValue(v);
  }
}

await api(patchUrl, {
  method: 'PATCH',
  body: JSON.stringify({
    fields: firestoreFields,
  }),
});

console.log(`\n✅ Berhasil mengonfigurasi ${updates.email || targetUid} sebagai Admin Pemantau (Monitoring / Read-Only)!`);

